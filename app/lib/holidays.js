export function getHoliday(dateKey) {
  // dateKey: YYYY-MM-DD
  const monthDay = dateKey.substring(5); // MM-DD
  
  if (HOLIDAYS_DYNAMIC[dateKey]) {
    return HOLIDAYS_DYNAMIC[dateKey];
  }
  
  if (HOLIDAYS_STATIC[monthDay]) {
    return HOLIDAYS_STATIC[monthDay];
  }

  // 정적 목록 범위 밖의 음력·대체공휴일은 유지보수되는 KR 달력으로 계산한다.
  const calculated = koreanHolidays.isHoliday(new Date(`${dateKey}T12:00:00+09:00`));
  if (!calculated) return null;
  const holiday = Array.isArray(calculated) ? calculated[0] : calculated;
  return holiday.name || '공휴일';
}
